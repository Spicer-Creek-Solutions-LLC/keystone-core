// gendocs/cli builds docs/project/CLI-REFERENCE.md from `<binary>
// --help` output. Walks every cmd/kscore-* directory, builds the
// binary into a temp dir, runs it with --help + recursively for
// each subcommand, and emits one section per binary.
//
// Stdlib only — no cobra introspection — so the lint stays simple
// and the source-of-truth is the live --help string each binary
// emits. Drift detection: re-run + git diff (the make docs-sync
// target).
//
// Usage:
//
//	go run ./tools/gendocs/cli > docs/project/CLI-REFERENCE.md
package main

import (
	"bufio"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const header = `# CLI reference

Generated by ` + "`make docs-sync`" + ` from ` + "`tools/gendocs/cli`" + `.
Source of truth is each binary's live ` + "`--help`" + ` output. Do not edit by hand —
` + "`make docs-sync`" + ` re-runs the generator and ` + "`git diff`" + ` will catch drift.

Every binary under ` + "`cmd/kscore-*`" + ` is enumerated below with its top-level
help text and every documented subcommand. ` + "`kscorectl`" + ` dispatches to
` + "`kscore-<name>`" + ` binaries via the plugin pattern, so each ` + "`kscore-<name>`" + `
section is also reachable as ` + "`kscorectl <name>`" + `.

`

func main() {
	cmdDir := "cmd"
	entries, err := os.ReadDir(cmdDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendocs/cli: read cmd/:", err)
		os.Exit(1)
	}

	bins := []string{}
	for _, e := range entries {
		if e.IsDir() && strings.HasPrefix(e.Name(), "kscore") {
			bins = append(bins, e.Name())
		}
	}
	sort.Strings(bins)

	tmpDir, err := os.MkdirTemp("", "gendocs-cli-")
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendocs/cli: tempdir:", err)
		os.Exit(1)
	}
	defer func() { _ = os.RemoveAll(tmpDir) }()

	out := &strings.Builder{}
	out.WriteString(header)
	out.WriteString("## Binaries\n\n")
	for _, bin := range bins {
		fmt.Fprintf(out, "- [%s](#%s)\n", bin, anchor(bin))
	}
	out.WriteString("\n")

	for _, bin := range bins {
		fmt.Fprintln(os.Stderr, "gendocs/cli: building", bin)
		binPath := filepath.Join(tmpDir, bin)
		// #nosec G204 -- bin is constrained to cmd/kscore-* entries
		// enumerated from the repo's own filesystem (read above).
		buildCmd := exec.Command("go", "build", "-o", binPath, "./"+filepath.Join(cmdDir, bin)) //nolint:gosec
		buildCmd.Env = append(os.Environ(), "CGO_ENABLED=0")
		if buildOut, err := buildCmd.CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "gendocs/cli: build %s: %v\n%s\n", bin, err, buildOut)
			os.Exit(1)
		}

		fmt.Fprintf(out, "## %s\n\n", bin)
		root := captureHelp(binPath, nil)
		if root == "" {
			out.WriteString("_(no help output)_\n\n")
			continue
		}
		out.WriteString("```\n")
		out.WriteString(root)
		out.WriteString("```\n\n")

		subs := parseSubcommands(root)
		if len(subs) == 0 {
			continue
		}
		fmt.Fprintf(out, "### %s subcommands\n\n", bin)
		for _, sub := range subs {
			subHelp := captureHelp(binPath, []string{sub})
			fmt.Fprintf(out, "#### %s %s\n\n", bin, sub)
			if subHelp == "" {
				out.WriteString("_(no help output)_\n\n")
				continue
			}
			out.WriteString("```\n")
			out.WriteString(subHelp)
			out.WriteString("```\n\n")
		}
	}

	// Trim trailing blank lines — markdownlint's MD012 fires on
	// double-newline-at-EOF.
	body := strings.TrimRight(out.String(), "\n") + "\n"
	if _, err := os.Stdout.WriteString(body); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs/cli: write stdout:", err)
		os.Exit(1)
	}
}

// captureHelp runs <bin> <args...> --help and returns stdout.
// Returns "" on failure (printed to stderr).
func captureHelp(bin string, args []string) string {
	full := append([]string{}, args...)
	full = append(full, "--help")
	// #nosec G204 -- building our own binaries from cmd/kscore-* paths walked above.
	c := exec.Command(bin, full...) //nolint:gosec
	c.Env = append(os.Environ(), "KSCORE_GENDOCS=1")
	out, _ := c.CombinedOutput() // many binaries exit non-zero on --help; that's ok
	return string(out)
}

// commandsHeader matches the "Available Commands:" line cobra emits.
var commandsHeader = regexp.MustCompile(`(?m)^Available Commands:\s*$`)

// commandLine matches each subcommand row: `  name   one-line description`.
var commandLine = regexp.MustCompile(`(?m)^  ([a-zA-Z][a-zA-Z0-9_-]*)\s{2,}`)

// parseSubcommands extracts subcommand names from cobra's --help
// output. Returns nil if no subcommands section is found. Skips
// the generic `help` subcommand.
func parseSubcommands(help string) []string {
	loc := commandsHeader.FindStringIndex(help)
	if loc == nil {
		return nil
	}
	rest := help[loc[1]:]
	scan := bufio.NewScanner(strings.NewReader(rest))
	var out []string
	seen := map[string]bool{}
	for scan.Scan() {
		line := scan.Text()
		if strings.TrimSpace(line) == "" {
			break // blank line marks end of section
		}
		// Cobra indents continuation lines; only the first indent
		// (2 spaces + name) is a subcommand.
		m := commandLine.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		name := m[1]
		if name == "help" || seen[name] {
			continue
		}
		seen[name] = true
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

// anchor builds a github-style markdown anchor from a heading.
func anchor(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '-':
			b.WriteRune('-')
		default:
			// drop other chars
		}
	}
	return b.String()
}
