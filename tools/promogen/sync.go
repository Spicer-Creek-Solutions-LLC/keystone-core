package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

// generatedHeader is prepended to every rendered tape. VHS treats `#`
// as a comment, so this is inert at render time and only exists to
// stop someone hand-editing a file the next sync would overwrite.
const generatedHeader = `# Code generated by tools/promogen; DO NOT EDIT.
# Source: %s
# Regenerate with: make update-promo
`

// SyncResult reports what a sync pass did, so --check can fail on
// drift the way docs-sync-check does.
type SyncResult struct {
	// Written are tapes whose content changed (or that did not exist).
	Written []string
	// Unchanged are tapes already matching their template output.
	Unchanged []string
}

// SyncTapes renders every assets/promo/tapes/*.tape.tmpl against facts.
//
// Templates exist so no card hard-codes a version, a module count, or
// a release status. Terminal tapes that run real commands need no
// template and simply have no .tmpl alongside them.
//
// When dryRun is true nothing is written; the result still reports
// which files would change.
func SyncTapes(promoDir string, facts *Facts, dryRun bool) (*SyncResult, error) {
	pattern := filepath.Join(promoDir, "tapes", "*.tape.tmpl")
	templates, err := filepath.Glob(pattern)
	if err != nil {
		return nil, fmt.Errorf("promogen: glob templates: %w", err)
	}
	sort.Strings(templates)

	res := &SyncResult{}
	for _, tmplPath := range templates {
		outPath := strings.TrimSuffix(tmplPath, ".tmpl")
		rendered, err := renderTape(tmplPath, promoDir, facts)
		if err != nil {
			return nil, err
		}

		// #nosec G304 G703 -- outPath is derived from a glob over the promo dir.
		existing, readErr := os.ReadFile(outPath)
		if readErr == nil && bytes.Equal(existing, rendered) {
			res.Unchanged = append(res.Unchanged, relTo(promoDir, outPath))
			continue
		}
		if readErr != nil && !os.IsNotExist(readErr) {
			return nil, fmt.Errorf("promogen: read %s: %w", outPath, readErr)
		}

		res.Written = append(res.Written, relTo(promoDir, outPath))
		if dryRun {
			continue
		}
		// #nosec G306 G703 G706 -- outPath comes from a glob over the promo dir;
		// the rendered tape is committed source, not a secret.
		if err := os.WriteFile(outPath, rendered, 0o644); err != nil {
			return nil, fmt.Errorf("promogen: write %s: %w", outPath, err)
		}
	}
	return res, nil
}

func renderTape(tmplPath, promoDir string, facts *Facts) ([]byte, error) {
	// #nosec G304 G703 -- tmplPath comes from a glob over the promo dir.
	raw, err := os.ReadFile(tmplPath)
	if err != nil {
		return nil, fmt.Errorf("promogen: read %s: %w", tmplPath, err)
	}
	// Missing keys are an error rather than a silent "<no value>"
	// baked into a frame of the finished video.
	//
	// #nosec G708 -- the template is committed repo source authored by
	// maintainers and reviewed like any other file, and it renders a VHS
	// tape rather than anything served to a user. Not attacker-controlled
	// input. `#nosec` rather than `//nolint:gosec` because `make
	// security-sast` runs the standalone gosec binary, which honours only
	// the former; golangci-lint honours both.
	t, err := template.New(filepath.Base(tmplPath)).
		Option("missingkey=error").
		Parse(string(raw))
	if err != nil {
		return nil, fmt.Errorf("promogen: parse %s: %w", tmplPath, err)
	}
	var body bytes.Buffer
	fmt.Fprintf(&body, generatedHeader, relTo(promoDir, tmplPath))
	if err := t.Execute(&body, facts); err != nil {
		return nil, fmt.Errorf("promogen: render %s: %w", tmplPath, err)
	}
	return body.Bytes(), nil
}

func relTo(base, path string) string {
	rel, err := filepath.Rel(base, path)
	if err != nil {
		return path
	}
	return rel
}
