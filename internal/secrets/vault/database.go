// ConfigurePostgreSQL configures a PostgreSQL database connection.
func (d *DatabaseEngine) ConfigurePostgreSQL(ctx context.Context, name string, config *PostgreSQLConfig) error {
	if name == "" {
		return fmt.Errorf("connection name is required")
	}
	if config == nil || config.ConnectionURL == "" {
		return fmt.Errorf("connection URL is required")
	}

	path := fmt.Sprintf("%s/config/%s", d.config.MountPath, name)

	data := map[string]interface{}{
		"plugin_name":    "postgresql-database-plugin",
		"connection_url": config.ConnectionURL,
		"allowed_roles":  "*",
	}

	if config.MaxOpenConnections > 0 {
		data["max_open_connections"] = config.MaxOpenConnections
	}
	if config.MaxIdleConnections > 0 {
		data["max_idle_connections"] = config.MaxIdleConnections
	}
	if config.MaxConnectionLifetime > 0 {
		data["max_connection_lifetime"] = config.MaxConnectionLifetime.String()
	}
	if config.Username != "" {
		data["username"] = config.Username
	}
	if config.Password != "" {
		data["password"] = config.Password
	}
	if config.UsernameTemplate != "" {
		data["username_template"] = config.UsernameTemplate
	}
	if config.DisableEscaping {
		data["disable_escaping"] = true
	}

	_, err := d.client.Write(ctx, path, data)
	return err
}

