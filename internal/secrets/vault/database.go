// CreateRole creates a dynamic database role.
func (d *DatabaseEngine) CreateRole(ctx context.Context, name string, role *DatabaseRole) error {
	if name == "" {
		return fmt.Errorf("role name is required")
	}
	if role == nil || role.DBName == "" {
		return fmt.Errorf("database connection name is required")
	}
	if len(role.CreationStatements) == 0 {
		return fmt.Errorf("creation statements are required")
	}

	path := fmt.Sprintf("%s/roles/%s", d.config.MountPath, name)

	data := map[string]interface{}{
		"db_name":             role.DBName,
		"creation_statements": role.CreationStatements,
	}

	if role.DefaultTTL > 0 {
		data["default_ttl"] = int(role.DefaultTTL.Seconds())
	}
	if role.MaxTTL > 0 {
		data["max_ttl"] = int(role.MaxTTL.Seconds())
	}
	if len(role.RevocationStatements) > 0 {
		data["revocation_statements"] = role.RevocationStatements
	}
	if len(role.RenewStatements) > 0 {
		data["renew_statements"] = role.RenewStatements
	}
	if len(role.RollbackStatements) > 0 {
		data["rollback_statements"] = role.RollbackStatements
	}

	_, err := d.client.Write(ctx, path, data)
	return err
}

