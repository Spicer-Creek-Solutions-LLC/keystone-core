// DatabaseType represents a supported database type.
type DatabaseType string

const (
	DatabaseTypePostgreSQL DatabaseType = "postgresql"
	DatabaseTypeMySQL      DatabaseType = "mysql"
	DatabaseTypeMongoDB    DatabaseType = "mongodb"
	DatabaseTypeMSSQL      DatabaseType = "mssql"
	DatabaseTypeOracle     DatabaseType = "oracle"
	DatabaseTypeRedshift   DatabaseType = "redshift"
	DatabaseTypeCassandra  DatabaseType = "cassandra"
	DatabaseTypeElastic    DatabaseType = "elasticsearch"
	DatabaseTypeSnowflake  DatabaseType = "snowflake"
)

// DatabaseCredentials represents credentials generated by the database secret engine.
type DatabaseCredentials struct {
	// Username is the generated username.
	Username string `json:"username"`

	// Password is the generated password.
	Password string `json:"password"`

	// LeaseID is the Vault lease ID for these credentials.
	LeaseID string `json:"lease_id"`

	// LeaseDuration is how long the credentials are valid.
	LeaseDuration time.Duration `json:"lease_duration"`

	// Renewable indicates if the lease can be renewed.
	Renewable bool `json:"renewable"`

	// Metadata contains additional metadata about the credentials.
	Metadata map[string]string `json:"metadata,omitempty"`
}

// DatabaseConfig configures a database secret engine mount.
type DatabaseConfig struct {
	// MountPath is the mount path for the database engine (default: "database").
	MountPath string `json:"mount_path,omitempty"`

	// DefaultTTL is the default TTL for generated credentials.
	DefaultTTL time.Duration `json:"default_ttl,omitempty"`

	// MaxTTL is the maximum TTL for generated credentials.
	MaxTTL time.Duration `json:"max_ttl,omitempty"`
}

// DatabaseEngine provides methods for working with Vault's database secret engine.
type DatabaseEngine struct {
	client *Client
	config *DatabaseConfig
}

// NewDatabaseEngine creates a new database engine client.
func NewDatabaseEngine(client *Client, config *DatabaseConfig) *DatabaseEngine {
	if config == nil {
		config = &DatabaseConfig{}
	}
	if config.MountPath == "" {
		config.MountPath = "database"
	}
	return &DatabaseEngine{
		client: client,
		config: config,
	}
}

// GenerateCredentials generates database credentials for a role.
func (d *DatabaseEngine) GenerateCredentials(ctx context.Context, role string) (*DatabaseCredentials, error) {
	return d.GenerateCredentialsWithTTL(ctx, role, 0)
}

// GenerateCredentialsWithTTL generates database credentials with a specific TTL.
func (d *DatabaseEngine) GenerateCredentialsWithTTL(ctx context.Context, role string, ttl time.Duration) (*DatabaseCredentials, error) {
	if role == "" {
		return nil, fmt.Errorf("role is required")
	}

	path := fmt.Sprintf("%s/creds/%s", d.config.MountPath, role)

	resp, err := d.client.Read(ctx, path)
	if err != nil {
		return nil, fmt.Errorf("failed to generate credentials: %w", err)
	}

	return d.parseCredentials(resp)
}

