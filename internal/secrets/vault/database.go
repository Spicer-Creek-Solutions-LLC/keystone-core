// DatabaseRole represents a database role configuration.
type DatabaseRole struct {
	// Name is the role name.
	Name string `json:"name"`

	// DBName is the database connection name.
	DBName string `json:"db_name"`

	// DefaultTTL is the default TTL for credentials.
	DefaultTTL time.Duration `json:"default_ttl"`

	// MaxTTL is the maximum TTL for credentials.
	MaxTTL time.Duration `json:"max_ttl"`

	// CreationStatements are SQL statements to create a user.
	CreationStatements []string `json:"creation_statements"`

	// RevocationStatements are SQL statements to revoke a user.
	RevocationStatements []string `json:"revocation_statements"`

	// RenewStatements are SQL statements executed during renewal.
	RenewStatements []string `json:"renew_statements"`

	// RollbackStatements are SQL statements for rollback on failure.
	RollbackStatements []string `json:"rollback_statements"`
}

// parseRole parses a role response.
func (d *DatabaseEngine) parseRole(resp map[string]interface{}) (*DatabaseRole, error) {
	if resp == nil {
		return nil, secrets.ErrSecretNotFound
	}

	data, ok := resp["data"].(map[string]interface{})
	if !ok {
		return nil, fmt.Errorf("invalid role response")
	}

	role := &DatabaseRole{}

	if dbName, ok := data["db_name"].(string); ok {
		role.DBName = dbName
	}
	if dbNames, ok := data["db_name"].([]interface{}); ok && len(dbNames) > 0 {
		if name, ok := dbNames[0].(string); ok {
			role.DBName = name
		}
	}

	if defaultTTL, ok := data["default_ttl"].(float64); ok {
		role.DefaultTTL = time.Duration(defaultTTL) * time.Second
	}

	if maxTTL, ok := data["max_ttl"].(float64); ok {
		role.MaxTTL = time.Duration(maxTTL) * time.Second
	}

	role.CreationStatements = parseStringSlice(data, "creation_statements")
	role.RevocationStatements = parseStringSlice(data, "revocation_statements")
	role.RenewStatements = parseStringSlice(data, "renew_statements")
	role.RollbackStatements = parseStringSlice(data, "rollback_statements")

	return role, nil
}

// parseCredentials parses a credentials response.
func (d *DatabaseEngine) parseCredentials(resp map[string]interface{}) (*DatabaseCredentials, error) {
	if resp == nil {
		return nil, secrets.ErrSecretNotFound
	}

	creds := &DatabaseCredentials{
		Metadata: make(map[string]string),
	}

	// Parse data section
	if data, ok := resp["data"].(map[string]interface{}); ok {
		if username, ok := data["username"].(string); ok {
			creds.Username = username
		}
		if password, ok := data["password"].(string); ok {
			creds.Password = password
		}
	}

	// Parse lease information
	if leaseID, ok := resp["lease_id"].(string); ok {
		creds.LeaseID = leaseID
	}

	if leaseDuration, ok := resp["lease_duration"].(float64); ok {
		creds.LeaseDuration = time.Duration(leaseDuration) * time.Second
	}

	if renewable, ok := resp["renewable"].(bool); ok {
		creds.Renewable = renewable
	}

	return creds, nil
}

// parseStringSlice parses a string slice from a map.
func parseStringSlice(data map[string]interface{}, key string) []string {
	val, ok := data[key]
	if !ok {
		return nil
	}

	switch v := val.(type) {
	case []interface{}:
		result := make([]string, 0, len(v))
		for _, item := range v {
			if s, ok := item.(string); ok {
				result = append(result, s)
			}
		}
		return result
	case []string:
		return v
	default:
		return nil
	}
}

// ToSecret converts DatabaseCredentials to a Secret.
func (c *DatabaseCredentials) ToSecret(path string) *secrets.Secret {
	secret := &secrets.Secret{
		Path:    path,
		Backend: secrets.BackendTypeVault,
		Type:    secrets.SecretTypeDatabase,
		Data: map[string]interface{}{
			"username": c.Username,
			"password": c.Password,
		},
		Metadata:  c.Metadata,
		Renewable: c.Renewable,
	}

	if c.LeaseID != "" {
		secret.Lease = &secrets.Lease{
			ID:         c.LeaseID,
			SecretPath: path,
			Backend:    secrets.BackendTypeVault,
			State:      secrets.LeaseStateActive,
			TTL:        c.LeaseDuration,
			IssuedAt:   time.Now(),
			ExpiresAt:  time.Now().Add(c.LeaseDuration),
			Renewable:  c.Renewable,
			Revocable:  true,
		}
	}

	return secret
}

