// ErrIdentifier is returned for an agent identifier the subject grammar refuses
// or that is reserved for a service principal.
var ErrIdentifier = errors.New("identifier is not usable as a subject token")

// ErrAgentPublicKey is returned when an agent identity is offered without a
// usable NATS public key. There is no fallback that generates one: generating
// it here is the defect this error exists to make impossible.
var ErrAgentPublicKey = errors.New("agent identity needs the agent's own NATS public key")

// AgentKey is one permanent agent identity, named by its identifier and its
// NATS public key.
//
// THE PUBLIC HALF IS ALL THERE IS. ADR-0003 § 4 has the agent generate its NATS
// NKey on the agent and send only the public half, and states the consequence
// this type exists to preserve: "no private key the agent uses is ever
// generated by, transmitted to, or recoverable from the server", which is why a
// compromised server can mint a NEW identity and cannot become an existing one.
//
// A generator that created the keypair itself would reverse that. It did, until
// review of C03-I1 found it: every agent seed was written into the deployment
// directory, and a server holding that directory could impersonate any agent
// that had ever been provisioned.
type AgentKey struct {
	ID        string
	PublicKey string
}

// Config is what a deployment supplies. Agents and Tokens are the identities
// that exist at generation time; C05 mints further agent identities against the
// account signing key as enrollment completes.
type Config struct {
	FleetSize int64
	Agents    []AgentKey
	Tokens    []string

	// RevokedTokens name bootstrap identities revoked in the account JWT, with
	// the operator key, at generation time. Under RFC 0005 this is the OFFLINE
	// path -- the generator's or the broker administrator's -- and never the
	// product's: the server cannot sign an account revocation, and bootstrap
	// access ends by refusal and expiry instead. NEG-7 exercises it.
	RevokedTokens []string

	// BootstrapTTL is ADR-0003 § 8's short expiry. Under RFC 0005 it is how
	// bootstrap access normally ends, at every enrollment, not only a backstop
	// behind a revocation.
	BootstrapTTL time.Duration

	// Limits defaults to DefaultLimits(FleetSize) when nil.
	Limits *Limits

	// BrokerNames are the names the broker's TLS certificate carries, and a
	// client verifies the broker against one of them (ADR-0002 § 12). Required:
	// there is no default name.
	BrokerNames []string

	// RuntimeDir is the absolute path at which the broker will find the
	// directory Write produces. The broker resolves certificate paths against
	// its working directory, not the configuration file, so the configuration
	// has to name them absolutely. Required.
	RuntimeDir string

	// CALifetime defaults to DefaultCALifetime when zero. BrokerCertLifetime
	// defaults, when zero, to DefaultBrokerCertLifetime or CALifetime, whichever
	// is shorter. A negative value, or an explicit broker lifetime longer than
	// the CA's, is ErrLifetime -- never the default.
	CALifetime         time.Duration
	BrokerCertLifetime time.Duration
}

// Identity is one NATS principal: its JWT, the permission lists that JWT
// carries, and -- for the identities this side legitimately creates -- its seed.
//
// Seed is EMPTY for a permanent agent, because ADR-0003 § 4 keeps that key on
// the agent. Service roles and bootstrap identities are the server's to issue,
// so theirs are here.
type Identity struct {
	Name      string
	PublicKey string
	Seed      []byte
	JWT       string
	Pub       []string
	Sub       []string
}

// Account is the Keystone or system account. SigningSeed is the account signing
// key ADR-0002 § 2 places with the server; the operator seed is not here and
// never is.
type Account struct {
	Name        string
	PublicKey   string
	JWT         string
	Seed        []byte
	SigningSeed []byte
	SigningKey  string
}

// Deployment is everything generation produces. OperatorSeed is returned to the
// CALLER and is never written by Write: ADR-0002 § 2 holds it outside every
// Keystone process, and GEN-7 is the case that checks the artifacts agree.
//
// CAKey is returned to the caller for the same reason and is never written by
// Write either. Whoever holds it can issue a certificate every client accepts
// as the broker; where it goes -- an HSM, a KMS, a vault, offline media -- is
// the administrator's decision, and nothing the deployment runs may hold it.
type Deployment struct {
	OperatorSeed      []byte
	OperatorPublicKey string
	OperatorJWT       string

	CAKey      []byte
	TLS        TLSMaterial
	RuntimeDir string

	System   Account
	Keystone Account

	Services   map[Principal]Identity
	Agents     map[string]Identity
	Bootstraps map[string]Identity

	Revoked []string
	Limits  Limits
}

// Generate produces a complete authorization set. It creates keys, so two calls
// never agree; nothing in it is derived from a committed fixture.
func Generate(cfg Config) (*Deployment, error) {
	for _, agent := range cfg.Agents {
		if err := ValidateAgentIdentifier(agent.ID); err != nil {
			return nil, err
		}
		if !nkeys.IsValidPublicUserKey(agent.PublicKey) {
			return nil, fmt.Errorf("agent %q: %w", agent.ID, ErrAgentPublicKey)
		}
	}
	for _, token := range cfg.Tokens {
		if err := ValidateAgentIdentifier(token); err != nil {
			return nil, fmt.Errorf("enrollment token %q: %w", token, err)
		}
	}
	if cfg.BootstrapTTL <= 0 {
		cfg.BootstrapTTL = 15 * time.Minute
	}
	limits := DefaultLimits(cfg.FleetSize)
	if cfg.Limits != nil {
		limits = *cfg.Limits
	}
	// Validated whether supplied or defaulted. A bad default is as capable of
	// signing an account with no bound on anything as a bad argument, and
	// checking only the argument would trust the one nobody passes.
	if err := limits.Validate(); err != nil {
		return nil, err
	}
	// TLS last among the checks: every input a refusal test targets is validated
	// before it, so a caller that omits the broker's names cannot be refused
	// for the wrong reason and still satisfy a test of another rule.
	if !path.IsAbs(cfg.RuntimeDir) {
		return nil, fmt.Errorf("%w: %q", ErrRuntimeDir, cfg.RuntimeDir)
	}
	tlsMaterial, caKey, err := newTLS(cfg.BrokerNames, cfg.CALifetime, cfg.BrokerCertLifetime, time.Now())
	if err != nil {
		return nil, err
	}

	operator, err := nkeys.CreateOperator()
	if err != nil {
		return nil, fmt.Errorf("create operator: %w", err)
	}
	operatorPub, err := operator.PublicKey()
	if err != nil {
		return nil, fmt.Errorf("operator public key: %w", err)
	}
	operatorSeed, err := operator.Seed()
	if err != nil {
		return nil, fmt.Errorf("operator seed: %w", err)
	}

	system, err := newAccount("SYS", operator, nil)
	if err != nil {
		return nil, fmt.Errorf("system account: %w", err)
	}
	keystone, err := newAccount("KEYSTONE", operator, &limits)
	if err != nil {
		return nil, fmt.Errorf("keystone account: %w", err)
	}

	operatorClaims := jwt.NewOperatorClaims(operatorPub)
	operatorClaims.Name = "keystone"
	operatorClaims.SystemAccount = system.PublicKey
	operatorJWT, err := operatorClaims.Encode(operator)
	if err != nil {
		return nil, fmt.Errorf("encode operator: %w", err)
	}

	d := &Deployment{
		OperatorSeed:      operatorSeed,
		OperatorPublicKey: operatorPub,
		OperatorJWT:       operatorJWT,
		CAKey:             caKey,
		TLS:               tlsMaterial,
		RuntimeDir:        cfg.RuntimeDir,
		System:            system,
		Keystone:          keystone,
		Services:          map[Principal]Identity{},
		Agents:            map[string]Identity{},
		Bootstraps:        map[string]Identity{},
		Limits:            limits,
	}

	minter, err := NewMinter(keystone.PublicKey, keystone.SigningSeed)
	if err != nil {
		return nil, err
	}

	for _, p := range Services() {
		identity, err := newUser(string(p), serviceGrants(p), minter, time.Time{})
		if err != nil {
			return nil, fmt.Errorf("service %s: %w", p, err)
		}
		d.Services[p] = identity
	}
	for _, agent := range cfg.Agents {
		identity, err := minter.Agent(agent)
		if err != nil {
			return nil, fmt.Errorf("agent %s: %w", agent.ID, err)
		}
		d.Agents[agent.ID] = identity
	}
	for _, token := range cfg.Tokens {
		identity, err := minter.Bootstrap(token, time.Now().Add(cfg.BootstrapTTL))
		if err != nil {
			return nil, fmt.Errorf("bootstrap %s: %w", token, err)
		}
		d.Bootstraps[token] = identity
	}

	if err := d.revoke(cfg.RevokedTokens, operator); err != nil {
		return nil, err
	}
	return d, nil
}

// ValidateAgentIdentifier refuses what ADR-0004 § 1's grammar refuses and what
// ADR-0005 § 3 reserves.
//
// It delegates rather than restating: internal/protocol already implements the
// grammar and holds the reserved-token list, and a second copy here would be a
// second thing to drift. WHERE the identifier comes from is not settled --
// ADR-0004 § 1 requires it server-assigned and ADR-0003 establishes no such
// identifier -- and C03 consumes one rather than deciding that.
func ValidateAgentIdentifier(id string) error {
	if !protocol.ValidIdentifier(id) {
		return fmt.Errorf("%q: %w", id, ErrIdentifier)
	}
	if protocol.ReservedSender(id) {
		return fmt.Errorf("%q is reserved for a service principal: %w", id, ErrIdentifier)
	}
	return nil
}

func newAccount(name string, operator nkeys.KeyPair, limits *Limits) (Account, error) {
	kp, err := nkeys.CreateAccount()
	if err != nil {
		return Account{}, err
	}
	pub, err := kp.PublicKey()
	if err != nil {
		return Account{}, err
	}
	seed, err := kp.Seed()
	if err != nil {
		return Account{}, err
	}
	signing, err := nkeys.CreateAccount()
	if err != nil {
		return Account{}, err
	}
	signingPub, err := signing.PublicKey()
	if err != nil {
		return Account{}, err
	}
	signingSeed, err := signing.Seed()
	if err != nil {
		return Account{}, err
	}

	claims := jwt.NewAccountClaims(pub)
	claims.Name = name
	claims.SigningKeys.Add(signingPub)
	if limits != nil {
		applyAccountLimits(claims, *limits)
	}
	encoded, err := claims.Encode(operator)
	if err != nil {
		return Account{}, err
	}
	return Account{
		Name:        name,
		PublicKey:   pub,
		JWT:         encoded,
		Seed:        seed,
		SigningSeed: signingSeed,
		SigningKey:  signingPub,
	}, nil
}

func applyAccountLimits(claims *jwt.AccountClaims, limits Limits) {
	claims.Limits.Conn = limits.Account.MaxConnections
	claims.Limits.Subs = limits.Account.MaxSubscriptions
	claims.Limits.Payload = limits.Account.MaxPayloadBytes
	claims.Limits.DiskStorage = limits.Account.MaxJetStreamDiskByte
	claims.Limits.MemoryStorage = 0
	// Data is the account's total byte budget; JetStream storage is bounded
	// separately above and ADR-0002 § 9 requires neither to be infinite.
	claims.Limits.Data = limits.Account.MaxJetStreamDiskByte
}

// revoke re-encodes the Keystone account with each named bootstrap identity in
// its revocation list. A revocation lives in the account JWT, so that is the
// artifact that changes, and only the operator key may sign it: this runs at
// generation time, outside the deployment. RFC 0005 makes it the offline path
// and not the product's -- the server's account signing key cannot do this.
func (d *Deployment) revoke(tokens []string, operator nkeys.KeyPair) error {
	if len(tokens) == 0 {
		return nil
	}
	claims, err := jwt.DecodeAccountClaims(d.Keystone.JWT)
	if err != nil {
		return fmt.Errorf("decode keystone account: %w", err)
	}
	for _, token := range tokens {
		identity, ok := d.Bootstraps[token]
		if !ok {
			return fmt.Errorf("revoke %q: no bootstrap identity was generated for it", token)
		}
		claims.Revoke(identity.PublicKey)
		d.Revoked = append(d.Revoked, identity.PublicKey)
	}
	sort.Strings(d.Revoked)
	encoded, err := claims.Encode(operator)
	if err != nil {
		return fmt.Errorf("re-encode keystone account: %w", err)
	}
	d.Keystone.JWT = encoded
	return nil
}

// applyPermissions writes a grant set onto a claim.
//
// AN EMPTY ALLOW LIST DOES NOT DENY. NATS reads a permission with no allow
// entries as UNRESTRICTED, not as "nothing permitted", so a principal
// ADR-0004 § 4 gives no grants in a direction would be free to act in that
// direction however it liked. The presence consumer and the monitoring role are
// both "Publish: none" in that table, and before this both could publish a
// command -- which is NEG-15's property, live in a generated deployment.
//
// ADR-0004 § 7 requires this: "a direction with no grants is rendered as an
// explicit deny of the whole subject space". That sentence exists because of
// this defect -- G46 put it there after C03-I2 measured it, and corrected § 4,
// which had said an omission already denied and so described a mechanism NATS
// does not have. An explicit deny of `>` is what makes the table's "none" mean
// none.
//
// Found at C03-I2 by the control publish every positive case synchronises on:
// two cases failed because the broker did not refuse a subject nobody should
// have been able to reach.
func applyPermissions(claims *jwt.UserClaims, g grants) {
	claims.Permissions.Pub = permissionFor(g.pub)
	claims.Permissions.Sub = permissionFor(g.sub)
}

func permissionFor(allow []string) jwt.Permission {
	if len(allow) == 0 {
		return jwt.Permission{Deny: jwt.StringList{">"}}
	}
	return jwt.Permission{Allow: append(jwt.StringList{}, allow...)}
}
